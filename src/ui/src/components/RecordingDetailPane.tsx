import React from 'react';
import {
  X,
  FileText,
  Clock,
  Calendar,
  Users,
  FolderTree,
  Sliders,
  Sparkles,
} from 'lucide-react';
import { PipelineProgressBar } from './PipelineProgressBar';

export interface RecordingDetailItem {
  id: string;
  date: string;
  title: string;
  duration: string;
  domain: 'Work' | 'Personal';
  customer?: string;
  project?: string;
  speakers: string[];
  status: string;
  routedPath: string;
  transcript?: string;
  activeStage?: 'Transcribing' | 'Diarizing' | 'Classifying' | 'Summarizing';
  metadata?: Record<string, unknown>;
  summary?: string;
}

export interface RecordingDetailPaneProps {
  recording: RecordingDetailItem | null;
  onClose: () => void;
  className?: string;
}

export const RecordingDetailPane: React.FC<RecordingDetailPaneProps> = ({
  recording,
  onClose,
  className = '',
}) => {
  if (!recording) {
    return null;
  }

  const metadataEntries = Object.entries(recording.metadata || {});

  return (
    <aside
      className={`bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-xl flex flex-col gap-5 text-slate-100 ${className}`}
      aria-label="Recording Details"
    >
      {/* Header */}
      <div className="flex items-start justify-between gap-3 border-b border-slate-800 pb-4">
        <div>
          <span
            className={`inline-flex px-2 py-0.5 rounded text-xs font-semibold mb-2 ${
              recording.domain === 'Work'
                ? 'bg-blue-950 text-blue-300 border border-blue-800'
                : 'bg-emerald-950 text-emerald-300 border border-emerald-800'
            }`}
          >
            {recording.domain}
          </span>
          <h2 className="text-xl font-bold tracking-tight text-white leading-snug">
            {recording.title}
          </h2>
          <div className="flex items-center gap-4 text-xs text-slate-400 mt-1">
            <span className="flex items-center gap-1">
              <Calendar className="w-3.5 h-3.5" />
              {recording.date}
            </span>
            <span className="flex items-center gap-1">
              <Clock className="w-3.5 h-3.5" />
              {recording.duration}
            </span>
          </div>
        </div>

        <button
          type="button"
          onClick={onClose}
          aria-label="Close detail pane"
          className="text-slate-400 hover:text-white p-1.5 rounded-lg hover:bg-slate-800 transition"
        >
          <X className="w-5 h-5" />
        </button>
      </div>

      {/* Processing indicator */}
      {recording.activeStage && (
        <div className="p-3 bg-amber-950/30 border border-amber-800/60 rounded-lg">
          <span className="text-xs font-semibold uppercase tracking-wider text-amber-400 block mb-1">
            Live Pipeline Stage
          </span>
          <PipelineProgressBar stage={recording.activeStage} status={recording.status} />
        </div>
      )}

      {/* Metadata Badges & Routing */}
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs bg-slate-950/60 p-3 rounded-lg border border-slate-800/80">
        <div>
          <span className="text-slate-400 block font-medium">Customer</span>
          <span className="text-slate-200">{recording.customer || '—'}</span>
        </div>
        <div>
          <span className="text-slate-400 block font-medium">Project</span>
          <span className="text-slate-200">{recording.project || '—'}</span>
        </div>
        <div className="sm:col-span-2">
          <span className="text-slate-400 flex items-center gap-1 font-medium mb-0.5">
            <Users className="w-3.5 h-3.5" /> Speakers
          </span>
          <span className="text-slate-200">
            {recording.speakers.length > 0 ? recording.speakers.join(', ') : 'None detected'}
          </span>
        </div>
        <div className="sm:col-span-2">
          <span className="text-slate-400 flex items-center gap-1 font-medium mb-0.5">
            <FolderTree className="w-3.5 h-3.5" /> Routed Vault Path
          </span>
          <code className="text-[11px] font-mono text-indigo-300 break-all block bg-slate-900 px-2 py-1 rounded border border-slate-800">
            {recording.routedPath}
          </code>
        </div>
      </div>

      {/* Summary */}
      <section>
        <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-2 flex items-center gap-1.5">
          <Sparkles className="w-3.5 h-3.5 text-indigo-400" />
          Summary
        </h3>
        <div className="p-3 bg-slate-950 border border-slate-800 rounded-lg text-sm text-slate-200 leading-relaxed">
          {recording.summary || (
            <p className="text-slate-400 italic">
              Executive Markdown summary generated by local LM Studio runtime upon pipeline classification.
            </p>
          )}
        </div>
      </section>

      {/* Transcript */}
      <section>
        <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-2 flex items-center gap-1.5">
          <FileText className="w-3.5 h-3.5 text-indigo-400" />
          Full Transcript
        </h3>
        <div className="p-3.5 bg-slate-950 border border-slate-800 rounded-lg text-sm text-slate-200 leading-relaxed max-h-60 overflow-y-auto whitespace-pre-wrap font-sans">
          {recording.transcript ? (
            recording.transcript
          ) : (
            <span className="text-slate-500 italic">No transcript content available.</span>
          )}
        </div>
      </section>

      {/* Metadata Key-Value Display */}
      <section>
        <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-2 flex items-center gap-1.5">
          <Sliders className="w-3.5 h-3.5 text-indigo-400" />
          Pipeline Metadata
        </h3>
        {metadataEntries.length > 0 ? (
          <dl className="grid grid-cols-1 gap-2 p-3 bg-slate-950 border border-slate-800 rounded-lg text-xs">
            {metadataEntries.map(([key, value]) => (
              <div key={key} className="flex flex-col sm:flex-row sm:items-baseline justify-between gap-1 py-1 border-b border-slate-900 last:border-b-0">
                <dt className="text-slate-400 font-mono text-[11px] capitalize">{key}:</dt>
                <dd className="text-slate-200 font-mono text-[11px] break-all sm:text-right">
                  {typeof value === 'object' && value !== null
                    ? JSON.stringify(value)
                    : String(value)}
                </dd>
              </div>
            ))}
          </dl>
        ) : (
          <p className="text-xs text-slate-500 italic">No metadata available</p>
        )}
      </section>
    </aside>
  );
};

export default RecordingDetailPane;
