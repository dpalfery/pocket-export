using PocketExport.Core.Models;

namespace PocketExport.Core.Taxonomy;

/// <summary>
/// Provides taxonomy loading and recording classification capabilities using local LLM inference.
/// </summary>
public interface ITaxonomyClassifier
{
    /// <summary>
    /// Loads and parses the taxonomy configuration from the vault root or ledger directory.
    /// </summary>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>The deserialized taxonomy configuration.</returns>
    /// <exception cref="FileNotFoundException">Thrown when the taxonomy YAML configuration file is not found.</exception>
    Task<TaxonomyConfig> LoadTaxonomyAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Classifies a recording transcript and metadata against the loaded taxonomy hierarchy using LM Studio chat completions.
    /// </summary>
    /// <param name="transcript">The text transcript of the recording.</param>
    /// <param name="speakers">The list of identified speakers.</param>
    /// <param name="pocketSummary">The preliminary summary generated by Pocket.</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>The structured classification result.</returns>
    Task<ClassificationResult> ClassifyRecordingAsync(
        string transcript,
        IReadOnlyList<string> speakers,
        string pocketSummary,
        CancellationToken cancellationToken = default);
}
